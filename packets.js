// IOTBT "E0" string lights (product 0xC5, Aurelux app). Protocol and scene payloads
// come from 8none1/lednetwf_ble (MIT, issue #126 capture of the Aurelux app).

// 8-byte transport header: flags, seq, frag control 80 00, length, length + 1, cmd family 0x0A.
function wrap(payload, seq) {
  const n = payload.length;
  return Buffer.concat([Buffer.from([0x00, seq & 0xff, 0x80, 0x00, n >> 8, n & 0xff, (n + 1) & 0xff, 0x0a]), payload]);
}

const power = (on) => Buffer.from([0xe0, 0x01, 0x00, on ? 0x23 : 0x24, ...Array(10).fill(0)]);

// hue 0-360, sat 0-100, value 1-100 — the same ranges HomeKit uses.
function color(hue, sat, value) {
  const packed = (Math.round(hue) << 7) | Math.round(sat);
  const v = Math.max(1, Math.min(100, Math.round(value)));
  return Buffer.from([0xe0, 0x01, 0x00, 0xc1, packed >> 8, packed & 0xff, v, 0, 0, 0, 0, 0x14, 0, 0]);
}

